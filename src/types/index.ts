// ── Enums ─────────────────────────────────────────────────────────────────────

export type UserRole =
  | "super_admin"   // Platform owner — full access
  | "country_rep"   // Regional rep — read-only admin dashboard, filtered by country
  | "company_admin" // Legal rep of a company (CEO or HR) — manages employees
  | "employee"      // Under a company subscription — theme controlled by company if locked
  | "individual";   // Self-paying — full control over card and theme

export type UserStatus      = "pending" | "active" | "suspended";
export type OrderStatus     = "pending" | "approved" | "shipped" | "delivered";
export type BillingCycle    = "monthly" | "annual";
export type SubscriptionStatus = "active" | "inactive" | "cancelled";
export type InvitationStatus   = "pending" | "accepted" | "expired";

export type DeviceType = "mobile" | "tablet" | "desktop" | "unknown";

export type EventType =
  | "view"             // Card page opened
  | "nfc_tap"          // Arrived via NFC chip (?source=nfc)
  | "qr_scan"          // Arrived via QR code (?source=qr)
  | "vcf_download"     // Save contact button clicked
  | "contact_exchange" // Visitor submitted their contact details
  | "social_click"     // A social link icon clicked
  | "share";           // Card shared (future)

// ── Identity & access ─────────────────────────────────────────────────────────

export interface Profile {
  id:         string;
  role:       UserRole;
  status:     UserStatus;
  username:   string;
  full_name:  string;
  email:      string;
  avatar_url: string | null;
  created_at: string;
  updated_at: string;
}

export interface Company {
  id:                    string;
  name:                  string;
  slug:                  string;
  logo_url:              string | null;
  brand_color:           string | null;
  industry:              string | null;
  website:               string | null;
  size:                  string | null;
  description:           string | null;
  status:                UserStatus;
  /** If true, employees under this company cannot change their card theme_color */
  theme_locked:          boolean;
  /** Captured at registration — legal rep confirmation checkbox */
  legal_rep_confirmed:   boolean;
  /** Optional company-level social links — shared across all employees */
  social_links:          SocialLinks | null;
  created_at:            string;
  updated_at:            string;
}

/**
 * Links a profile (country_rep role) to a country code.
 * A country rep can only view users/companies in their assigned country.
 */
export interface CountryRep {
  id:           string;
  profile_id:   string;
  country_code: string;  // ISO 3166-1 alpha-2 e.g. "RW", "UG", "KE"
  country_name: string;
  created_at:   string;
}

/**
 * Many-to-many: a user can be linked to multiple companies.
 * is_primary = true → this company shows in the card top-right badge.
 * Any user can link to any company — no company confirmation required.
 * Company only controls card if the employee is under their subscription.
 */
export interface ProfileCompany {
  id:            string;
  profile_id:    string;
  company_id:    string;
  department_id: string | null;
  job_title:     string | null;  // Role at this specific company
  is_primary:    boolean;
  created_at:    string;
}

/** An editable affiliation group on a digital card. Max 3 per card. */
export interface CardGroup {
  id:                string;
  card_id:           string;
  organization_name: string;
  job_title:         string | null;
  social_links:      SocialLinks;
  show_on_card:      boolean;
  sort_order:        number;
  created_at:        string;
  updated_at:        string;
}

export interface Department {
  id:         string;
  company_id: string;
  name:       string;
  color:      string | null;
  created_at: string;
}

/**
 * One-time-use invite links generated by company admins.
 * Token expires after 7 days and can only be used once.
 */
export interface Invitation {
  id:          string;
  company_id:  string;
  created_by:  string;         // profile_id of the company admin
  email:       string | null;  // Optional — pre-fills the registration form
  token:       string;         // Unique one-time token in the invite URL
  status:      InvitationStatus;
  expires_at:  string;
  accepted_by: string | null;  // profile_id of the employee who accepted
  created_at:  string;
}

