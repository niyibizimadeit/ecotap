/**
 * Monthly environmental impact report per company.
 * Calculated using industry-standard figures (see INSTRUCTIONS.md).
 * Stored so historical trends can be tracked — not recomputed retroactively.
 */
export interface EnvironmentalReport {
  id:                   string;
  company_id:           string;
  report_month:         string;   // YYYY-MM
  active_cards:         number;   // Employee cards active during this month
  cards_in_circulation: number;   // Total physical cards ever ordered (full lifecycle count)
  paper_cards_avoided:  number;   // Estimated paper cards not printed
  co2_saved_grams:      number;   // Grams of CO₂ avoided
  water_saved_litres:   number;   // Litres of water not consumed
  waste_avoided_grams:  number;   // Grams of paper waste avoided
  trees_saved:          number;   // Fractional tree equivalent
  cumulative_co2_grams: number;   // Running total since joining
  cumulative_cards:     number;   // Running total cards avoided
  email_sent:           boolean;
  email_sent_at:        string | null;
  created_at:           string;
}

